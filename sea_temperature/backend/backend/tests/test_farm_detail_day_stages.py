"""Check daily heat stages without database or network access."""
import unittest

from backend.farm_detail import day_stages


class DayStagesTest(unittest.TestCase):
    def test_temperature_boundaries(self):
        for temperature, expected in (
            (24.9, {"stage": 0, "streak28": 0}),
            (25.0, {"stage": 1, "streak28": 0}),
            (25.1, {"stage": 1, "streak28": 0}),
            (27.9, {"stage": 1, "streak28": 0}),
            (28.0, {"stage": 2, "streak28": 1}),
            (28.1, {"stage": 2, "streak28": 1}),
            (None, {"stage": 0, "streak28": 0}),
        ):
            with self.subTest(temperature=temperature):
                self.assertEqual(day_stages([temperature], []), [expected])

    def test_alert_starts_on_third_hot_day_and_continues(self):
        self.assertEqual(day_stages([28.0, 28.5, 29.0, 28.0], []), [
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
            {"stage": 3, "streak28": 3},
            {"stage": 3, "streak28": 4},
        ])

    def test_cooler_day_resets_alert_and_streak(self):
        self.assertEqual(day_stages([27.9, 28.0, 28.0, 28.0], [28.0] * 3), [
            {"stage": 1, "streak28": 0},
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
            {"stage": 3, "streak28": 3},
        ])

    def test_missing_day_resets_alert_and_streak(self):
        self.assertEqual(day_stages([None, 28.0, 28.0, 28.0], [28.0] * 3), [
            {"stage": 0, "streak28": 0},
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
            {"stage": 3, "streak28": 3},
        ])

    def test_lookback_contributes_to_streak_but_not_output(self):
        self.assertEqual(day_stages([28.0, 28.5], [28.0, 29.0]), [
            {"stage": 3, "streak28": 3},
            {"stage": 3, "streak28": 4},
        ])

    def test_only_unbroken_tail_of_lookback_counts(self):
        for interruption in (27.9, None):
            with self.subTest(interruption=interruption):
                self.assertEqual(
                    day_stages([28.0], [28.0, 28.0, interruption, 28.0]),
                    [{"stage": 2, "streak28": 2}],
                )

    def test_empty_values_return_no_days_even_with_lookback(self):
        for lookback in ([], [28.0, 28.0, 28.0]):
            with self.subTest(lookback=lookback):
                self.assertEqual(day_stages([], lookback), [])

    def test_input_lists_are_not_modified(self):
        values = [28.0, None, 25.0]
        lookback = [28.0, 29.0]
        day_stages(values, lookback)
        self.assertEqual(values, [28.0, None, 25.0])
        self.assertEqual(lookback, [28.0, 29.0])

    def test_thresholds_use_unrounded_temperatures(self):
        for temperature, expected in (
            (24.9999, {"stage": 0, "streak28": 0}),
            (25.0001, {"stage": 1, "streak28": 0}),
            (27.9999, {"stage": 1, "streak28": 0}),
            (28.0, {"stage": 3, "streak28": 3}),
            (28.0001, {"stage": 3, "streak28": 3}),
        ):
            with self.subTest(temperature=temperature):
                self.assertEqual(day_stages([temperature], [28.0, 28.0]), [expected])

    def test_seven_day_reference_scenario(self):
        # Synthetic labels are fixed from the documented rules, not generated by the function.
        values = [28.0, 29.1, 27.9, 24.9, 25.0, 28.0, 28.2]
        expected = [
            {"stage": 3, "streak28": 3},
            {"stage": 3, "streak28": 4},
            {"stage": 1, "streak28": 0},
            {"stage": 0, "streak28": 0},
            {"stage": 1, "streak28": 0},
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
        ]
        result = day_stages(values, [28.3, 28.1])
        self.assertEqual(len(result), len(expected))
        for day, (actual, reference) in enumerate(zip(result, expected), start=1):
            with self.subTest(day=day, temperature=values[day - 1]):
                self.assertEqual(actual, reference)

    def test_scattered_hot_days_do_not_accumulate_into_alert(self):
        self.assertEqual(day_stages([29.0, 28.0, 27.0, 30.0, None, 29.0, 28.0], []), [
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
            {"stage": 1, "streak28": 0},
            {"stage": 2, "streak28": 1},
            {"stage": 0, "streak28": 0},
            {"stage": 2, "streak28": 1},
            {"stage": 2, "streak28": 2},
        ])


if __name__ == "__main__":
    unittest.main()
